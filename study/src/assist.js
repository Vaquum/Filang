// Editor assistance derived from registry signatures: friendly labels and completions.
// Pure functions (no DOM) so they are shared by both editors and tested in Node.

import { printExpr, tokenizePrefix } from './lang.js';
import { ENUMS } from './registry.js';

export function argFor(call, def, pname) {
  for (const a of call.args) {
    const n = a.name === null ? def && def.positional : a.name;
    if (n === pname) return a;
  }
  return null;
}

function valueText(n, reg) {
  if (n.k === 'choices') return n.items.map((x) => printExpr(x)).join(' | ');
  if (n.k === 'vec') return n.items.map((x) => printExpr(x)).join(', ');
  if (n.k === 'call') return nodeLabel(n, reg);
  return printExpr(n);
}

/** Friendly label generated by a definition's template (canonical text stays the source of truth). */
export function nodeLabel(node, reg) {
  switch (node.k) {
    case 'str': {
      const nd = reg.getNamed(node.value);
      if (!nd) return JSON.stringify(node.value);
      const def = nd.patternId ? reg.getPattern(nd.patternId) : reg.get(nd.def);
      const disp = {};
      for (const p of def.params) disp[p.name] = nd.args[p.name] ?? p.default;
      return `${node.value} — ${def.template(disp)}`;
    }
    case 'call': {
      const def = reg.get(node.name);
      if (!def || def.status === 'planned' || !def.template) return printExpr(node);
      const disp = {};
      for (const p of def.params) {
        const a = argFor(node, def, p.name);
        disp[p.name] = a ? valueText(a.value, reg) : (p.default ?? '?');
      }
      return def.template(disp);
    }
    case 'cmp': {
      const enumFor = (n) => (n.k === 'call' ? (n.name === 'weekday' ? ENUMS.SessionDay : n.name === 'completed_trend' ? ENUMS.Trend : null) : null);
      const e = enumFor(node.left) || enumFor(node.right);
      const side = (n) => (n.k === 'id' && e && e.labels[n.name] ? e.labels[n.name] : n.k === 'choices' && e ? n.items.map((x) => (x.k === 'id' && e.labels[x.name]) || printExpr(x)).join(' | ') : nodeLabel(n, reg));
      return `${side(node.left)} ${node.op === '=' ? 'is' : node.op === '!=' ? 'is not' : node.op} ${side(node.right)}`;
    }
    case 'and': case 'or': return node.items.map((x) => nodeLabel(x, reg)).join(` ${node.k} `);
    case 'not': return `not (${nodeLabel(node.item, reg)})`;
    case 'choices': return `one of ${node.items.map((x) => printExpr(x)).join(' | ')}`;
    default: return printExpr(node);
  }
}

// ---------------------------------------------------------------- completions

const DURATIONS = ['15m', '30m', '1h', '2h', '4h', '12h', '24h', '48h'];

function eventItems(reg) {
  const out = [];
  for (const [name, nd] of reg.named) if (nd.kind === 'event') out.push({ label: JSON.stringify(name), insert: JSON.stringify(name), detail: `named ${nd.def}@${nd.version}` });
  for (const f of reg.implemented()) if (f.kind === 'event') out.push({ label: f.name, insert: f.example, detail: f.title });
  return out;
}

/** Text that is a valid where condition for a definition (categoricals are compared with a value). */
export function whereExample(f) {
  if (f.kind === 'categorical' && !/=/.test(f.example)) return `${f.example} = ${ENUMS[f.result.slice(4)].values[0]}`;
  return f.example;
}

function conditionItems(reg) {
  const out = [];
  for (const f of reg.implemented()) {
    if (f.kind === 'condition' || f.kind === 'categorical') out.push({ label: f.name, insert: whereExample(f), detail: f.status === 'extension' ? `${f.title} (extension v${f.version})` : f.title });
  }
  for (const [name, nd] of reg.named) if (nd.kind === 'state') out.push({ label: JSON.stringify(name), insert: JSON.stringify(name), detail: 'state sampled at the anchor' });
  return out;
}

function groupItems(reg) {
  return reg.implemented()
    .filter((f) => f.kind === 'categorical' || f.kind === 'condition')
    .map((f) => ({ label: f.name, insert: f.kind === 'categorical' ? f.example.replace(/\s*=.*$/, '') : f.example, detail: f.kind === 'categorical' ? `${f.title} (categorical)` : `${f.title} (Boolean)` }));
}

function outcomeItems(reg) {
  return reg.implemented().filter((f) => f.kind === 'outcome').map((f) => ({ label: f.name, insert: f.example, detail: f.title }));
}

function valueItems(param, reg, env) {
  switch (param.type) {
    case 'Duration': return (param.list ? ['[1h, 4h]', ...DURATIONS] : DURATIONS).map((d) => ({ label: d, insert: d, detail: param.list ? 'horizon (vector = columns)' : 'duration' }));
    case 'Ratio': return [param.default || '35%', '2%', '3%'].filter((x, i, a) => a.indexOf(x) === i).map((d) => ({ label: d, insert: d, detail: 'ratio' }));
    case 'Calendar': return [...env.calendars.keys()].map((c) => ({ label: c, insert: c, detail: 'calendar' }));
    case 'State': return [
      ...[...reg.named].filter(([, nd]) => nd.kind === 'state').map(([n]) => ({ label: JSON.stringify(n), insert: JSON.stringify(n), detail: 'named state' })),
      ...reg.implemented().filter((f) => f.kind === 'state').map((f) => ({ label: f.name, insert: f.example, detail: 'typed state' })),
    ];
    default: return [];
  }
}

function markArg(top, ctx, k) {
  const t = ctx[k];
  if (t && t.t === 'id' && ctx[k + 1] && ctx[k + 1].t === 'p' && ctx[k + 1].v === ':') top.used.push(t.v);
  else if (top.first) top.positionalUsed = true;
  top.argStart = false;
}

/**
 * Completions at a caret position. Returns { from, to, items: [{label, insert, detail}] };
 * inserting replaces text.slice(from, to).
 */
export function completionsAt(text, caret, reg, env) {
  const toks = tokenizePrefix(text.slice(0, caret)).filter((t) => t.t !== 'eof');
  let partial = '';
  let from = caret;
  let ctx = toks;
  const last = toks[toks.length - 1];
  if (last && (last.t === 'id' || last.t === 'kw') && last.end === caret) {
    partial = last.v;
    from = last.start;
    ctx = toks.slice(0, -1);
  } else if (last && last.t === 'str' && last.end === caret) {
    return { from: caret, to: caret, items: [] };
  }
  const stack = [];
  let clause = null;
  for (let k = 0; k < ctx.length; k++) {
    const t = ctx[k];
    if (t.t === 'kw' && ['on', 'let', 'find', 'where', 'by', 'measure'].includes(t.v) && stack.length === 0) clause = t.v;
    if (t.t === 'p' && t.v === '(') {
      if (stack.length && stack[stack.length - 1].argStart) markArg(stack[stack.length - 1], ctx, k - 1);
      stack.push({ call: ctx[k - 1] && ctx[k - 1].t === 'id' ? ctx[k - 1].v : null, used: [], positionalUsed: false, argStart: true, first: true });
      continue;
    }
    if (t.t === 'p' && t.v === ')') { stack.pop(); continue; }
    const top = stack[stack.length - 1];
    if (!top) continue;
    if (t.t === 'p' && t.v === ',') { top.argStart = true; top.first = false; continue; }
    if (top.argStart && !(t.t === 'id' && ctx[k + 1] && ctx[k + 1].t === 'p' && ctx[k + 1].v === '(')) markArg(top, ctx, k);
  }
  const prev = ctx[ctx.length - 1];
  const prev2 = ctx[ctx.length - 2];
  let items = [];
  const top = stack[stack.length - 1];
  if (top && top.call) {
    const def = reg.get(top.call);
    if (def && def.params && prev) {
      if (prev.t === 'p' && (prev.v === '(' || prev.v === ',')) {
        const firstArg = prev.v === '(';
        items = def.params.filter((p) => !top.used.includes(p.name) && !(top.positionalUsed && def.positional === p.name))
          .map((p) => ({ label: `${p.name}:`, insert: `${p.name}: `, detail: `${p.type}${p.list ? ' or [..]' : ''}${p.default ? ` (default ${p.default})` : p.required ? ' (required)' : ''}` }));
        if (firstArg && def.positional) {
          const pp = def.params.find((p) => p.name === def.positional);
          items = [...valueItems(pp, reg, env).map((x) => ({ ...x, detail: `${def.positional} (positional)` })), ...items];
        }
      } else if (prev.t === 'p' && prev.v === ':' && prev2 && prev2.t === 'id') {
        const p = def.params.find((x) => x.name === prev2.v);
        if (p) items = valueItems(p, reg, env);
      }
    }
  } else if (!stack.length && prev) {
    if (prev.t === 'kw' && prev.v === 'find') items = eventItems(reg);
    else if (prev.t === 'kw' && ['where', 'and', 'or', 'not'].includes(prev.v)) items = conditionItems(reg);
    else if (prev.t === 'kw' && prev.v === 'by') items = groupItems(reg);
    else if (prev.t === 'kw' && prev.v === 'group') items = [{ label: 'by', insert: 'by ', detail: 'group by' }];
    else if (prev.t === 'kw' && prev.v === 'measure') items = outcomeItems(reg);
    else if (prev.t === 'kw' && prev.v === 'on') items = [{ label: env.recording.instrument, insert: `${env.recording.instrument} `, detail: env.recording.venue }];
    else if (prev.t === 'op' && (prev.v === '=' || prev.v === '!=')) {
      let k = ctx.length - 2;
      let name = null;
      if (ctx[k] && ctx[k].t === 'p' && ctx[k].v === ')') {
        let depth = 0;
        for (; k >= 0; k--) {
          if (ctx[k].t === 'p' && ctx[k].v === ')') depth++;
          else if (ctx[k].t === 'p' && ctx[k].v === '(') { depth--; if (depth === 0) { name = ctx[k - 1] && ctx[k - 1].v; break; } }
        }
      }
      const e = name === 'weekday' ? ENUMS.SessionDay : name === 'completed_trend' ? ENUMS.Trend : null;
      if (e) items = e.values.map((v) => ({ label: v, insert: v, detail: e.labels[v] }));
    } else if (prev.t === 'id' && clause === 'on' && prev2 && prev2.t === 'kw' && prev2.v === 'on') {
      items = [{ label: env.recording.barText, insert: `${env.recording.barText}\n`, detail: 'bar size' }];
    } else if (clause === 'on' && prev.t === 'dur') {
      items = [{ label: 'find', insert: 'find ', detail: 'event' }, { label: 'let', insert: 'let ', detail: 'binding' }];
    } else if (prev.t === 'p' || prev.t === 'dur' || prev.t === 'str' || prev.t === 'num' || prev.t === 'id') {
      const kws = clause === 'measure' ? ['measure'] : clause === 'by' ? ['measure'] : clause === 'let' ? ['let', 'find'] : ['where', 'and', 'or', 'group by', 'measure'];
      items = kws.map((k) => ({ label: k, insert: `${k} `, detail: 'keyword' }));
    }
  } else if (!prev) {
    items = [{ label: 'on', insert: `on ${env.recording.instrument} ${env.recording.barText}\n`, detail: 'start a question' }];
  }
  if (partial) items = items.filter((x) => x.label.replace(/^"/, '').startsWith(partial) || x.insert.startsWith(partial));
  return { from, to: caret, items: items.slice(0, 10) };
}
